#include <stdio.h>
#include<stdlib.h>
#include <unistd.h>
#include <string.h>
#include "prompt/prompt.h"
#include "builtins/builtins.h"
#include "search/search.h"
#include "ls/ls.h"
#include "pinfo/pinfo.h"


int main()
{
    char home[2000];
    char prev[2000];
    prev[0] = '\0';
    if (getcwd(home, sizeof(home)) == nullptr)
    {
        perror("home");
        return 1;
    }

    while (true)
    { // get the prompt
        print_prompt(home);

        //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

        // get users input
        char input[2000];
        char input_cpy[2000];
        if (fgets(input, sizeof(input), stdin) == nullptr)
        {
            perror("fgets");
            continue;
        }
        strcpy(input_cpy, input);
        //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

        // tokenize the inputs
        char *cmnd = strtok(input, " \t\n");
        ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

        // if no input is give

        if (cmnd == nullptr)
        {
            continue;
        }
        ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

        else if (strcmp(cmnd, "pwd") == 0)
        {
            pwd();
        }
        ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

        else if (strcmp(cmnd, "cd") == 0)
        {
            char *path = strtok(nullptr, " \t\n");

            char *extra_argu = strtok(nullptr, " \t\n");

            if (extra_argu != nullptr)
            {
                printf("INVALID ARGUMENTS\n");
                continue;
            }

            change_dir(path, home, prev);
        }

        ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

        else if (strcmp(cmnd, "echo") == 0)
        {
            char *stmt = input_cpy;
            while (*stmt == ' ' || *stmt == '\t')
                stmt++;

            echo(stmt);
        }
/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

        else if(strcmp(cmnd,"ls")==0)
        {
            char* ls_input = strtok(NULL," \t\n");
            
            main_ls(ls_input);
            
        }

        ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

        else if (strcmp(cmnd, "search") == 0)
        {
            char *path = strtok(NULL, " \t\n");
            char cwd[2000];
            if (getcwd(cwd, sizeof(cwd)) == nullptr)
            {
                perror("cwd");
                continue;
            }
            if(search(path, cwd))
                printf("True\n");

            else
                printf("False\n");
        }
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
	else if(strcmp(cmnd,"pinfo")==0)
	{
		char* pid = strtok(NULL," \t\n");
		if(pid==NULL)
		{
			pinfo(getpid());
		}

		else 
		{
			pid_t pid_n = atoi(pid);
			pinfo(pid_n);
		}
	}
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

        else if (strcmp(cmnd, "e") == 0 || strcmp(cmnd, "exit")==0)
        {
            break;
        }
/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////        
	
        else 
        {
            printf("command not found: %s\n",cmnd);
            continue;
        }
    }

    printf("exit from shell");

    return 0;
}
